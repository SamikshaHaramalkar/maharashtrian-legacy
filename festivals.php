        <div class="row">
            <div class="col-md-6 mb-4">
                <h2>Ganesh Chaturthi</h2>
                <img src="assets/img/images-2.jpeg" alt="Ganesh Chaturthi" class="img-fluid rounded">
                <p>One of the most popular festivals in Maharashtra, Ganesh Chaturthi marks the birth of Lord Ganesha, the god of wisdom and prosperity. The 10-day festival features grand processions, prayers, and cultural programs throughout the state, culminating in the immersion of Ganesha idols in water bodies.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Diwali</h2>
                <img src="assets/img/360_F_463368800_4W4oBJlk1WgdVPZ47pTLxH84HW1RqUpH.jpg" alt="Diwali" class="img-fluid rounded">
                <p>The festival of lights, Diwali, is widely celebrated across Maharashtra with decorative oil lamps, vibrant fireworks, and delicious sweets. It symbolizes the victory of light over darkness and good over evil, marking the return of Lord Rama to Ayodhya after defeating Ravana.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Gudi Padwa</h2>
                <img src="assets/img/16491354262008817256.jpg" alt="Gudi Padwa" class="img-fluid rounded">
                <p>Gudi Padwa marks the beginning of the Maharashtrian New Year and is celebrated with much enthusiasm. Colorful rangolis, traditional food, and the raising of the 'Gudi' flag are key highlights of this festival, symbolizing prosperity and good fortune.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Shivaji Jayanti</h2>
                <img src="assets/img/shivajiedit1_d.webp" alt="Shivaji Jayanti" class="img-fluid rounded">
                <p>Shivaji Jayanti is celebrated in honor of the legendary Maratha king, Chhatrapati Shivaji Maharaj. The event is marked by processions, patriotic speeches, and cultural performances that pay tribute to his legacy, inspiring pride and valor among the people of Maharashtra.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Navratri</h2>
                <img src="assets/img/navratri.jpg" alt="Navratri" class="img-fluid rounded">
                <p>Navratri is a nine-day festival celebrated with great zeal across Maharashtra. It honors the Goddess Durga, and includes traditional dances like Garba and Dandiya. Temples are beautifully decorated, and devotees fast during this auspicious period, seeking blessings and spiritual strength.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Krishna Janmashtami</h2>
                <img src="assets/img/krishna janmashtami.jpg" alt="Krishna Janmashtami" class="img-fluid rounded">
                <p>Krishna Janmashtami celebrates the birth of Lord Krishna. Maharashtra is known for its 'Dahi Handi' celebrations, where groups of people form human pyramids to break a pot filled with curd, symbolizing Krishna's playful nature and his love for butter and sweets.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Makar Sankranti</h2>
                <img src="assets/img/makar sankranti.jpg" alt="Makar Sankranti" class="img-fluid rounded">
                <p>Makar Sankranti marks the end of the winter solstice and is a harvest festival. People fly kites, prepare sweets made of sesame and jaggery, and exchange gifts, symbolizing the spreading of warmth and goodwill, and celebrating the harvest season.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Akshaya Tritiya</h2>
                <img src="assets/img/akshaya tritiya.jpg" alt="Akshaya Tritiya" class="img-fluid rounded">
                <p>Akshaya Tritiya is an auspicious day for starting new ventures and making investments. It is believed that anything started on this day will bring prosperity and success. Many families conduct weddings and buy gold, considering it a highly favorable time.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Holi</h2>
                <img src="assets/img/Holi.jpg" alt="Holi" class="img-fluid rounded">
                <p>Holi, the festival of colors, is celebrated with much enthusiasm across Maharashtra. People throw colored powders at each other, dance, and enjoy traditional delicacies like 'Puran Poli.' It symbolizes the victory of good over evil and the arrival of spring.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Rang Panchami</h2>
                <img src="assets/img/rang-panchami.jpg" alt="Rang Panchami" class="img-fluid rounded">
                <p>Rang Panchami is celebrated five days after Holi and marks the culmination of the spring festival. It involves playing with colors and water, accompanied by joyous celebrations and community gatherings, extending the festivities of Holi.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Ashadhi Ekadashi</h2>
                <img src="assets/img/ashadhi-ekadashi.jpg" alt="Ashadhi Ekadashi" class="img-fluid rounded">
                <p>Ashadhi Ekadashi is a spiritual festival observed by devotees of Lord Vithoba in Maharashtra. Pilgrims undertake a 'Wari,' a long procession on foot to Pandharpur, chanting devotional songs and offering prayers to Lord Vithoba, symbolizing devotion and faith.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Narali Purnima</h2>
                <img src="assets/img/narali-purnima.jpg" alt="Narali Purnima" class="img-fluid rounded">
                <p>Narali Purnima is a significant festival for the fishing community in Maharashtra. On this day, fishermen offer coconuts to the sea god, seeking blessings for a safe and bountiful fishing season. It marks the beginning of the fishing season.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Hartalika Teej</h2>
                <img src="assets/img/hartalika-teej.jpg" alt="Hartalika Teej" class="img-fluid rounded">
                <p>Hartalika Teej is a festival where women pray for the well-being of their husbands and a happy married life. They observe fasting and worship Goddess Parvati, who is considered a symbol of love and devotion, celebrating the bond of marriage.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Shravan Somvar</h2>
                <img src="assets/img/shravan-somvar.jpg" alt="Shravan Somvar" class="img-fluid rounded">
                <p>Shravan Somvar is a series of Mondays during the month of Shravan that are considered highly auspicious for Lord Shiva's devotees. They observe fasting and visit Shiva temples to offer prayers for health, wealth, and prosperity, reflecting deep devotion.</p>
            </div>

            <div class="col-md-6 mb-4">
                <h2>Tulsi Vivah</h2>
                <img src="assets/img/tulsi-vivah.jpg" alt="Tulsi Vivah" class="img-fluid rounded">
                <p>Tulsi Vivah symbolizes the wedding of the Tulsi plant to Lord Vishnu. It is celebrated in many households, especially among Vaishnavites, who perform rituals to honor the sacred plant, which is believed to bring prosperity and well-being.</p>
            </div>
